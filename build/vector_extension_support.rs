fn write_empty_vector_extension_support_file(
    vector_extension_support_file_path: &mut std::fs::File,
) {
    writeln!(
        vector_extension_support_file_path,
        "// Automaticly generated by build.rs. Do not edit.

// No vector extension support found, VLEN = 0.

pub const VLEN: usize = 0;

#[allow(unused_variables)]
pub const fn save_vector_registers(vcpu: *mut crate::vcpu::Vcpu) {{}}"
    )
    .unwrap();
}
