use std::io::Write;

pub fn generate_vector_extension_support(out_dir: &str, vlen: usize) {
    // Create the file path for the vector extension support code.
    let vector_extension_support_path_raw =
        std::path::Path::new(out_dir).join("vector_extension_support.rs");
    let mut vector_extension_support_path =
        std::fs::File::create(&vector_extension_support_path_raw).unwrap();

    // If VLEN size declared in the device tree file is 0,
    // vector extension support must not be added.
    if vlen > 0 {
        add_vector_extension_support(&mut vector_extension_support_path, vlen);
    } else {
        write_empty_vector_extension_support_file(&mut vector_extension_support_path);
    }
}

