use std::io::Write;

pub fn generate_hart_constants(out_dir: &str, harts: Vec<crate::Hart>, total_hart_capacity: usize) {
    // Create the file path for the hart constants.
    let hart_constants_file_path = std::path::Path::new(out_dir).join("hart_constants.rs");
    let mut hart_constants_file = std::fs::File::create(hart_constants_file_path).unwrap();

    let mut max_supported_assigned_guests_per_hart = 0;

    for hart in &harts {
        if hart.guests.len() > max_supported_assigned_guests_per_hart {
            max_supported_assigned_guests_per_hart = hart.guests.len();
        }
    }

    writeln!(
        hart_constants_file,
        "// Automaticly generated by build.rs. Do not edit.
use crate::multihart::Hart;

pub const MAX_SUPPORTED_ASSIGNED_GUESTS_PER_HART: usize = {max_supported_assigned_guests_per_hart};
pub const TOTAL_HART_CAPACITY: usize = {total_hart_capacity};

static HARTS: [Hart; TOTAL_HART_CAPACITY] = [
",
    )
    .unwrap();

    for hart in harts {
        writeln!(
            hart_constants_file ,
            "
Hart {{
    assigned_guests: core::cell::UnsafeCell::new([core::ptr::null_mut(); MAX_SUPPORTED_ASSIGNED_GUESTS_PER_HART]),
    guests: ["
        )
        .unwrap();
        for guest_id in &hart.guests {
            writeln!(hart_constants_file, "{guest_id:#?},").unwrap();
        }
        for _ in 0..(max_supported_assigned_guests_per_hart - hart.guests.len()) {
            writeln!(hart_constants_file, "None,").unwrap();
        }
        writeln!(hart_constants_file, "]}},").unwrap();
    }

    writeln!(hart_constants_file, "];").unwrap();
}
