use crate::build_modules::{
    hardware_dts_parser::{MemoryRegion, MmioPeripheral},
    main_dts_parser::HypervisorConfiguration,
};
use std::io::Write;

#[derive(Clone)]
struct MmioMemoryRegion {
    base_addr: u64,
    size: u64,
    emulation_fn: Option<String>,
}

// Custom Debug implementation to print 'emulation_fn' as a raw string without quotation marks.
impl core::fmt::Debug for MmioMemoryRegion {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        let emulation_fn_str = if let Some(ptr_str) = &self.emulation_fn {
            format!("Some({})", ptr_str)
        } else {
            "None".to_string()
        };
        f.debug_struct("MmioMemoryRegion")
            .field("base_addr", &format_args!("{}", self.base_addr))
            .field("size", &format_args!("{}", self.size))
            .field("emulation_fn", &format_args!("{}", emulation_fn_str))
            .finish()
    }
}
impl MmioMemoryRegion {
    pub fn empty() -> Self {
        Self {
            base_addr: 0,
            size: 0,
            emulation_fn: None,
        }
    }
    fn from_peripherals(
        peripherals: &Vec<MmioPeripheral>,
        drivers_config: &crate::build_modules::drivers::DriverConfig,
    ) -> Vec<Self> {
        let mut mmio_regions: Vec<Self> = Vec::new();
        for peripheral in peripherals {
            let compatible = &peripheral.compatible;

            // If the region policy is set to 'Emulate',
            // map it to the corresponding driver handler from the configuration.
            // Otherwise, default to None (hardware passthrough).
            let emulation_fn = if peripheral.is_emulate() {
                let emulation_fn_str = drivers_config
                    .mappings
                    .get(compatible)
                    .unwrap_or_else(|| {
                        panic!("Driver to the compatible field \"{compatible}\" must be set.")
                    })
                    .clone();
                Some(emulation_fn_str)
            } else {
                None
            };
            mmio_regions.push(Self {
                base_addr: peripheral.region.base_addr,
                size: peripheral.region.size,
                emulation_fn: emulation_fn.clone(),
            });
        }
        mmio_regions
    }
    fn from_passthroguh_regions(passthrough_regions: &Vec<MemoryRegion>) -> Vec<Self> {
        let mut mmio_regions: Vec<Self> = Vec::new();

        for region in passthrough_regions {
            let base_addr = region.base_addr;
            let size = region.size;
            mmio_regions.push(Self {
                base_addr,
                size,
                emulation_fn: None,
            });
        }

        mmio_regions
    }
}
pub fn generate_guest_constants(
    out_dir: &str,
    hypervisor_configuration: &mut HypervisorConfiguration,
    drivers_config: crate::build_modules::drivers::DriverConfig,
) {
    // Create the file path for the guest constants.
    let guest_constants_file_path = std::path::Path::new(out_dir).join("guest_constants.rs");
    let mut guest_constants_file = std::fs::File::create(guest_constants_file_path).unwrap();
    let guest_specific_routines_file_path =
        std::path::Path::new(out_dir).join("guest_specific_routines.rs");
    let mut guest_specific_routines_file =
        std::fs::File::create(guest_specific_routines_file_path).unwrap();
    write!(
        guest_specific_routines_file,
        "
// Automaticly generated by build.rs. Do not edit.\n\n"
    )
    .unwrap();

    let max_supported_harts_per_guest = hypervisor_configuration.max_supported_harts_per_guest;
    let max_supported_assigned_harts_per_guest =
        hypervisor_configuration.max_supported_assigned_harts_per_guest;
    let max_aligned_passthrough_mmio_regions_count =
        hypervisor_configuration.max_aligned_passthrough_mmio_regions_count;
    let max_allowed_mmio_peripherals_count =
        hypervisor_configuration.max_allowed_mmio_peripherals_count;
    let guests = &mut hypervisor_configuration.guests;
    let system_mmio_windows = &mut hypervisor_configuration.system_mmio_windows;

    writeln!(
        guest_constants_file,
        "// Automaticly generated by build.rs. Do not edit.
use crate::guest::MmioMemoryRegion;
pub const MAX_SUPPORTED_HARTS_PER_GUEST: usize = {max_supported_harts_per_guest};
pub const MAX_SUPPORTED_ASSIGNED_HARTS_PER_GUEST: usize = {max_supported_assigned_harts_per_guest};
pub const MAX_ALIGNED_PASSTHROUGH_REGIONS_COUNT: usize = {max_aligned_passthrough_mmio_regions_count};
pub const MAX_ALLOWED_MMIO_REGIONS_COUNT: usize = {max_allowed_mmio_peripherals_count};

pub const SYSTEM_MMIO_WINDOWS: [MmioMemoryRegion; {}] = {:#?};

pub static GUESTS: [Guest; {}] = [
",
        system_mmio_windows.len(),
        MmioMemoryRegion::from_passthroguh_regions(system_mmio_windows),
        guests.len(),
    )
    .unwrap();

    let manifest_dir = std::env::var("CARGO_MANIFEST_DIR").unwrap();

    for (guest_id, guest) in guests.iter_mut().enumerate() {
        generate_guest_specific_routine(
            guest_id,
            guest.vlen,
            guest.fp,
            &mut guest_specific_routines_file,
        );
        // Create guest.vcpus array.
        let mut vcpus: String = String::from("[");
        vcpus.push_str(
            "Some(crate::vcpu::Vcpu::zeroed()), "
                .repeat(guest.hart_capacity)
                .as_str(),
        );
        vcpus.push_str(
            "None, "
                .repeat(max_supported_harts_per_guest - guest.hart_capacity)
                .as_str(),
        );
        vcpus.push(']');

        // Extend 'assigned_harts' with default values up to MAX_SUPPORTED_ASSIGNED_HARTS_PER_GUEST.
        guest.assigned_harts.extend(vec![
            None;
            max_supported_assigned_harts_per_guest
                - guest.assigned_harts.len()
        ]);

        // Extend 'aligned_passthrough_mmio_regions' with default
        // values up to MAX_ALIGNED_PASSTHROUGH_MMIO_REGIONS_COUNT.
        guest.aligned_passthrough_mmio_regions.extend(vec![
            MemoryRegion::empty();
            max_aligned_passthrough_mmio_regions_count
                - guest
                    .aligned_passthrough_mmio_regions
                    .len()
        ]);

        // Left-pad 'allowed_mmio_regions' with defaults up to MAX_ALLOWED_MMIO_REGIONS.
        let mut allowed_mmio_regions = vec![
            MmioMemoryRegion::empty();
            max_allowed_mmio_peripherals_count
                - guest.allowed_mmio_peripherals.len()
        ];
        allowed_mmio_regions.extend(MmioMemoryRegion::from_peripherals(
            &guest.allowed_mmio_peripherals,
            &drivers_config,
        ));

        // Count the assigned HARTs, skipping None slots.
        let assigned_hart_count = guest.assigned_harts.iter().flatten().count();

        if assigned_hart_count > guest.hart_capacity {
            panic!("Assigned hart count cannot be bigger than general hart capacity.")
        }

        // Add guest entry in GUESTS array.
        writeln!(
            guest_constants_file,
            "Guest {{
    page_table: spin::Mutex::new(crate::guest_table::GuestPageTable::empty()),
    entry_gpa: {},
    active_hart_count: core::sync::atomic::AtomicUsize::new(0),
    active_assigned_hart_count: core::sync::atomic::AtomicUsize::new(0),
    hart_capacity: {},
    assigned_hart_capacity: {},
    assigned_harts: {:#?},
    data: include_bytes!(\"{manifest_dir}/{}\"),
    vcpus: core::cell::UnsafeCell::new({vcpus}),
    vcpu_ptrs: spin::Mutex::new([const {{ None }}; MAX_SUPPORTED_HARTS_PER_GUEST]),
    aligned_passthrough_mmio_regions: {:#?},
    allowed_mmio_memory_region: {allowed_mmio_regions:#?},
    guest_specific_trap_routine: crate::guest_{guest_id}_trap_routine,
    guest_specific_ret_routine: crate::guest_{guest_id}_ret_routine,

}},

",
            guest.entry_gpa,
            guest.hart_capacity - assigned_hart_count,
            assigned_hart_count,
            guest.assigned_harts,
            guest.path,
            MmioMemoryRegion::from_passthroguh_regions(&guest.aligned_passthrough_mmio_regions),
        )
        .unwrap();
    }

    writeln!(guest_constants_file, "];").unwrap();
}

fn generate_guest_specific_routine(
    guest_id: usize,
    vlen: usize,
    fp: bool,
    guest_specific_routines_file: &mut std::fs::File,
) {
    let mut trap_routine_function =
        format!("fn guest_{guest_id}_trap_routine(vcpu: *mut crate::vcpu::Vcpu) {{\n");
    let mut ret_routine_function =
        format!("fn guest_{guest_id}_ret_routine(vcpu: *mut crate::vcpu::Vcpu) {{\n");

    if vlen != 0 {
        trap_routine_function.push_str("extension_routines::save_vrs_if_needed(vcpu); \n");
        ret_routine_function.push_str("extension_routines::restore_vrs_if_needed(vcpu); \n");
    }
    if fp {
        trap_routine_function.push_str("extension_routines::save_fprs_if_needed(vcpu); \n");
        ret_routine_function.push_str("extension_routines::restore_fprs_if_needed(vcpu); \n");
    }

    trap_routine_function.push_str("}\n");
    ret_routine_function.push_str("}\n");

    write!(
        guest_specific_routines_file,
        "{ret_routine_function}
{trap_routine_function}"
    )
    .unwrap();
}
