use crate::build_modules::{
    arch::TargetArchGuestFeatures,
    hardware_dts_parser::{MemoryRegion, MmioPeripheral},
};

#[path = "build/mod.rs"]
mod build_modules;

pub static SUPPORTED_ARCHS: [&str; 2] = ["riscv64", "wasm32"];

#[macro_export]
macro_rules! root_dir {
    () => {
        "../"
    };
}

#[macro_export]
macro_rules! root_dir_from_out_relative {
    () => {
        "../../../../../../"
    };
}

pub const CONFIG_DTS_PATH: &str = concat!(root_dir!(), "config.dts");
pub const HARDWARE_DTS_PATH: &str = concat!(root_dir!(), "hardware.dts");
pub const MODULES_TOML_PATH: &str = concat!(root_dir!(), "modules.toml");

#[derive(Debug)]
struct Guest {
    entry_gpa: usize,
    hart_capacity: usize,
    assigned_harts: Vec<Option<u32>>,
    path: String,
    aligned_passthrough_mmio_regions: Vec<MemoryRegion>,
    allowed_mmio_peripherals: Vec<MmioPeripheral>,
    target_arch_guest_features: TargetArchGuestFeatures,
    allowed_to_write_shared_buffers: Option<Vec<u32>>,
    allowed_to_read_shared_buffers: Option<Vec<u32>>,
    notify_policy: Option<NotifyPolicy>,
}

#[derive(Debug)]
pub enum NotifyPolicy {
    Synchronous,
    Poll,
}

#[derive(Debug, Default)]
pub struct Hart {
    hart_id: usize,
    guests: Vec<Option<usize>>,
}

pub struct TargetArch {
    name: String,
}
impl TargetArch {
    pub fn is_riscv64(&self) -> bool {
        self.name == "riscv64"
    }
    pub fn is_wasm32(&self) -> bool {
        self.name == "wasm32"
    }

    pub fn get_required_modules(&self) -> Vec<String> {
        match self.name.as_str() {
            "riscv64" => vec!["claim_guest".to_string()],
            _ => unreachable!(),
        }
    }
}

fn main() {
    println!("cargo:rerun-if-changed=../config.dts");
    println!("cargo:rerun-if-changed=../hardware.dts");
    println!("cargo:rerun-if-changed=arch/riscv64/mmio/driver.rs");

    let out_dir = std::env::var("OUT_DIR")
        .expect("[FATAL][BUILD]: failed to determine the output directory from the environment");

    let codegen_out_dir = format!(
        "// Automaticly generated by build.rs. Do not edit.\n\n
#[macro_export]
macro_rules! codegen_out_dir {{
    () => {{ \"{out_dir}\" }};
}}"
    );

    std::fs::write(out_dir.clone() + "/codegen_out_dir.rs", codegen_out_dir)
        .expect("[FATAL][BUILD]: failed to perform a write to the file");

    let target_arch = TargetArch {
        name: std::env::var("CARGO_CFG_TARGET_ARCH")
            .expect("[FATAL][BUILD]: failed to determine the actual target architecture from the environment"),
    };

    if !SUPPORTED_ARCHS.contains(&target_arch.name.as_str()) {
        panic!(
            "[FATAL][BUILD]: {} architecture is not supported.",
            target_arch.name
        );
    }

    // Compile and parse the hardware device tree file.
    let memory_peripherals = build_modules::hardware_dts_parser::parse_dts(out_dir.as_str());

    // Compile and parse the main device tree file.
    let mut hypervisor_configuration = build_modules::config_dts_parser::parse_dts(
        out_dir.as_str(),
        &target_arch,
        memory_peripherals,
    );

    build_modules::guest_abi_constants::generate_guest_abi_constants(
        &out_dir,
        &hypervisor_configuration,
    );

    // Generate hart constants file.
    build_modules::hart_abi_constants::generate_hart_abi_constants(
        &out_dir,
        &hypervisor_configuration.harts,
        hypervisor_configuration.total_hart_capacity,
    );

    if !target_arch.is_wasm32() {
        build_modules::modules::generate_module_paths(&target_arch, &out_dir);

        build_modules::arch::generate_arch_support(
            &out_dir,
            &target_arch,
            &hypervisor_configuration.target_arch_features,
        );

        // Parse the driver configuration file.
        let drivers_config = crate::build_modules::drivers::parse();

        // Generate guest constants file.
        build_modules::guest_constants::generate_guest_constants(
            &out_dir,
            &mut hypervisor_configuration,
            &target_arch,
            drivers_config,
        );

        // Generate hart constants file.
        build_modules::hart_constants::generate_hart_constants(
            &out_dir,
            &hypervisor_configuration.harts,
        );
    }
}
