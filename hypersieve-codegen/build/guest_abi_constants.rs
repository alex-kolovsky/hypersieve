use crate::build_modules::main_dts_parser::HypervisorConfiguration;
use std::io::Write;

pub fn generate_guest_abi_constants(
    out_dir: &str,
    hypervisor_configuration: &HypervisorConfiguration,
) {
    let guest_abi_constants_file_path =
        std::path::Path::new(out_dir).join("guest_abi_constants.rs");
    let mut guest_abi_constants_file =
        std::fs::File::create(guest_abi_constants_file_path).unwrap();
    let max_supported_harts_per_guest = hypervisor_configuration.max_supported_harts_per_guest;
    let max_supported_assigned_harts_per_guest =
        hypervisor_configuration.max_supported_assigned_harts_per_guest;

    writeln!(
        guest_abi_constants_file,
        "// Automaticly generated by build.rs. Do not edit.
pub const MAX_SUPPORTED_HARTS_PER_GUEST: usize = {max_supported_harts_per_guest};
pub const MAX_SUPPORTED_ASSIGNED_HARTS_PER_GUEST: usize = {max_supported_assigned_harts_per_guest};
pub const GUESTS_COUNT: usize = {};
    ",
        hypervisor_configuration.guests.len(),
    )
    .unwrap();
}
