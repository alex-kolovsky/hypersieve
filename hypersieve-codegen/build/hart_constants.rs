use std::io::Write;

pub fn generate_hart_constants(out_dir: &str, harts: &Vec<crate::Hart>) {
    // Create the file path for the hart constants.
    let hart_constants_file_path = std::path::Path::new(out_dir).join("hart_constants.rs");
    let mut hart_constants_file = std::fs::File::create(hart_constants_file_path).unwrap();

    let mut max_supported_assigned_guests_per_hart = 0;

    for hart in harts {
        if hart.guests.len() > max_supported_assigned_guests_per_hart {
            max_supported_assigned_guests_per_hart = hart.guests.len();
        }
    }

    writeln!(
        hart_constants_file,
        "// Automaticly generated by build.rs. Do not edit.
use crate::multihart::Hart;
use hypersieve_abi::MAX_SUPPORTED_ASSIGNED_GUESTS_PER_HART;
use hypersieve_abi::TOTAL_HART_CAPACITY;
use hypersieve_abi::ASSIGNED_GUESTS_BY_HART_ID;

pub static HARTS: [Hart; TOTAL_HART_CAPACITY] = [
",
    )
    .unwrap();

    for hart in harts {
        let is_hart_assigned = !hart.guests.is_empty();
        writeln!(
            hart_constants_file ,
            "
Hart {{
    is_assigned: {is_hart_assigned},
    assigned_guest_vcpus: core::cell::UnsafeCell::new([const {{None}}; MAX_SUPPORTED_ASSIGNED_GUESTS_PER_HART]),
    guests: &ASSIGNED_GUESTS_BY_HART_ID[{}],
}},
        ",
        hart.hart_id,
        )
        .unwrap();
    }

    writeln!(hart_constants_file, "];").unwrap();
}
